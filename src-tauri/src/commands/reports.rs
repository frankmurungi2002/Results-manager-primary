pub struct ReportCardRequest {
    pub class_id: String,
    pub term_id: String,
    /// Empty means the whole class — the bulk case (FR-G12).
    #[serde(default)]
    pub student_ids: Vec<String>,
    /// Partial report: only the exams named here. Empty means the whole term
    /// (FR-D1's "partial and final").
    #[serde(default)]
    pub exam_ids: Vec<String>,
}

#[tauri::command]
pub fn build_report_cards(
    state: State<'_, AppState>,
    request: ReportCardRequest,
) -> AppResult<DocumentEnvelope<ReportCardBatch>> {
    let session = state.sessions.require()?;
    session.require_view_class(&request.class_id)?;

    let conn = state.db.lock();
    let mut batch = compute_report_cards(
        &conn,
        &request.class_id,
        &request.term_id,
        &request.exam_ids,
        false,
    )?;

    // A single-learner or partial request still ranks against the whole class —
    // a position is only meaningful relative to everyone.
    if !request.student_ids.is_empty() {
        batch
            .cards
            .retain(|card| request.student_ids.contains(&card.student_id));
    }

    audit::record(
        &conn,
        Some(&session),
        "report_card.build",
        "class",
        &request.class_id,
        format!(
            "Built {} report cards for {}, {}{}",
            batch.cards.len(),
            batch.class_name,
            batch.term_name,
            if batch.blocked.is_empty() {
                String::new()
            } else {
                format!(" ({} blocked on fees)", batch.blocked.len())
            }
        ),
    )?;

    envelope(&conn, "report_card", batch)
}

/// Every learner's card for one class and term, ranked.
///
/// `history` computes an earlier term only to compare against: it ignores
/// the fees block and does not look further back.
fn compute_report_cards(
    conn: &Connection,
    class_id: &str,
    term_id: &str,
    exam_ids: &[String],
    history: bool,
) -> AppResult<ReportCardBatch> {
    let year_id = repo::current_academic_year_id(&conn)?
        .ok_or_else(|| AppError::validation("No academic year is active yet."))?;

    // --- Context ------------------------------------------------------------
    let (class_name, level_kind, academic_year, term_name, term_seq): (
        String,
        String,
        String,
        String,
        i64,
    ) = conn.query_row(
        "SELECT c.name, c.level_kind, y.label, t.name, t.seq
         FROM classes c
         CROSS JOIN terms t
         JOIN academic_years y ON y.id = t.academic_year_id
         WHERE c.id = ?1 AND t.id = ?2",
        params![class_id, term_id],
        |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?, row.get(3)?, row.get(4)?)),
    )?;

    // The term after this one, in this year or the next.
    let next_term_begins: Option<String> = conn
        .query_row(
            "SELECT t.start_date
             FROM terms t
             JOIN academic_years y ON y.id = t.academic_year_id
             WHERE y.label > ?1 OR (y.label = ?1 AND t.seq > ?2)
             ORDER BY y.label ASC, t.seq ASC
             LIMIT 1",
            params![academic_year, term_seq],
            |row| row.get(0),
        )
        .optional()?
        .flatten();

    // --- Exams in scope -----------------------------------------------------
    let exams: Vec<(String, String, f64, bool)> = {
        let mut stmt = conn.prepare(
            "SELECT id, name, weight, is_final FROM exams WHERE term_id = ?1 ORDER BY seq ASC",
        )?;
        let all: Vec<(String, String, f64, bool)> = stmt
            .query_map(params![term_id], |row| {
                Ok((
                    row.get(0)?,
                    row.get(1)?,
                    row.get(2)?,
                    row.get::<_, i64>(3)? != 0,
                ))
            })?
            .collect::<rusqlite::Result<_>>()?;

        if exam_ids.is_empty() {
            all
        } else {
            all.into_iter()
                .filter(|(id, _, _, _)| exam_ids.contains(id))
                .collect()
        }
    };

    if exams.is_empty() {
        return Err(AppError::validation(
            "That term has no examinations to report on.",
        ));
    }

    // The same slots the PLE projector uses, so the two can never disagree
    // about a learner's term mark.
    let slots: Vec<ExamSlot> = exams
        .iter()
        .map(|(_, _, weight, is_final)| ExamSlot {
            weight: *weight,
            is_final: *is_final,
        })
        .collect();

    let is_final = exams.iter().any(|(_, _, _, final_flag)| *final_flag) && exam_ids.is_empty();

    // --- Subjects -----------------------------------------------------------
    struct SubjectMeta {
        id: String,
        name: String,
        is_core: bool,
        max_score: f64,
        pass_mark: f64,
        grading_system_id: String,
        teacher_name: Option<String>,
    }

    let subjects: Vec<SubjectMeta> = {
        let mut stmt = conn.prepare(
            "SELECT cs.id,
                    COALESCE(cs.display_name, s.name) AS name,
                    cs.is_core,
                    COALESCE(cs.max_score, s.max_score),
                    COALESCE(cs.pass_mark, s.pass_mark),
                    COALESCE(cs.grading_system_id, c.default_grading_system_id, 'gs_percentage'),
                    (SELECT u.full_name FROM teacher_assignments ta
                      JOIN users u ON u.id = ta.user_id
                      WHERE ta.class_id = cs.class_id AND ta.subject_id = cs.subject_id
                        AND ta.role = 'subject_teacher' AND ta.status = 'active' LIMIT 1)
             FROM class_subjects cs
             JOIN subjects s ON s.id = cs.subject_id
             JOIN classes c ON c.id = cs.class_id
             WHERE cs.class_id = ?1 AND cs.status = 'active'
             ORDER BY cs.is_core DESC, cs.position ASC",
        )?;
        let collected = stmt.query_map(params![class_id], |row| {
            Ok(SubjectMeta {
                id: row.get(0)?,
                name: row.get(1)?,
                is_core: row.get::<_, i64>(2)? != 0,
                max_score: row.get(3)?,
                pass_mark: row.get(4)?,
                grading_system_id: row.get(5)?,
                teacher_name: row.get(6)?,
            })
        })?
        .collect::<rusqlite::Result<_>>()?;
        collected
    };

    let systems: HashMap<String, GradingSystem> = repo::load_grading_systems_by_id(
        &conn,
        &subjects
            .iter()
            .map(|s| s.grading_system_id.clone())
            .collect::<Vec<_>>(),
    )?;

    // --- Learners -----------------------------------------------------------
    struct Learner {
        id: String,
        full_name: String,
        reg_number: String,
        gender: Option<String>,
        photo: Option<Vec<u8>>,
        stream_id: Option<String>,
        date_of_birth: Option<String>,
        stream_name: Option<String>,
        fees_blocked: bool,
        fees_note: Option<String>,
    }

    let learners: Vec<Learner> = {
        let mut stmt = conn.prepare(
            "SELECT s.id, s.full_name, s.reg_number, s.gender, s.photo_png,
                    st.name AS stream_name, s.fees_blocked, s.fees_note, e.stream_id,
                    s.date_of_birth
             FROM enrollments e
             JOIN students s ON s.id = e.student_id
             LEFT JOIN streams st ON st.id = e.stream_id
             WHERE e.class_id = ?1 AND e.academic_year_id = ?2 AND e.status = 'active'
             ORDER BY s.full_name COLLATE NOCASE ASC",
        )?;
        let collected = stmt.query_map(params![class_id, year_id], |row| {
            Ok(Learner {
                id: row.get(0)?,
                full_name: row.get(1)?,
                reg_number: row.get(2)?,
                gender: row.get(3)?,
                photo: row.get(4)?,
                stream_id: row.get(8)?,
                date_of_birth: row.get(9)?,
                stream_name: row.get(5)?,
                fees_blocked: row.get::<_, i64>(6)? != 0,
                fees_note: row.get(7)?,
            })
        })?
        .collect::<rusqlite::Result<_>>()?;
        collected
    };

    let class_size = learners.len() as i64;
    let photos_on = repo::feature_enabled(&conn, "student_photos")?;
    let fees_rule_on = repo::get_setting(&conn, "rule.fees_block")?.as_deref() == Some("on");

    // --- Marks, in one query for the whole class ----------------------------
    // key: (student_id, class_subject_id, exam_id)
    let mut marks: HashMap<(String, String, String), (Option<f64>, bool)> = HashMap::new();
    {
        let exam_list: Vec<String> = exams.iter().map(|(id, _, _, _)| id.clone()).collect();
        let mut stmt = conn.prepare(
            "SELECT m.student_id, m.class_subject_id, m.exam_id, m.score, m.is_absent
             FROM marks m
             JOIN class_subjects cs ON cs.id = m.class_subject_id
             WHERE cs.class_id = ?1",
        )?;
        let rows = stmt.query_map(params![class_id], |row| {
            Ok((
                row.get::<_, String>(0)?,
                row.get::<_, String>(1)?,
                row.get::<_, String>(2)?,
                row.get::<_, Option<f64>>(3)?,
                row.get::<_, i64>(4)? != 0,
            ))
        })?;
        for row in rows {
            let (student_id, class_subject_id, exam_id, score, absent) = row?;
            if exam_list.contains(&exam_id) {
                marks.insert((student_id, class_subject_id, exam_id), (score, absent));
            }
        }
    }

    // --- Attendance (FR-G9 feeding FR-D1) -----------------------------------
    let attendance: HashMap<String, (i64, i64)> = {
        let mut stmt = conn.prepare(
            "SELECT student_id,
                    SUM(CASE WHEN state IN ('present', 'late') THEN 1 ELSE 0 END),
                    COUNT(*)
             FROM attendance WHERE term_id = ?1 AND class_id = ?2
             GROUP BY student_id",
        )?;
        let collected = stmt.query_map(params![term_id, class_id], |row| {
            Ok((
                row.get::<_, String>(0)?,
                (row.get::<_, i64>(1)?, row.get::<_, i64>(2)?),
            ))
        })?
        .collect::<rusqlite::Result<_>>()?;
        collected
    };

    // --- Comments (FR-G11) --------------------------------------------------
    type Comments = (Option<String>, Option<String>, Option<String>);
    let comments: HashMap<String, Comments> = {
        let mut stmt = conn.prepare(
            "SELECT student_id, class_teacher_comment, head_teacher_comment, conduct_comment
             FROM report_comments WHERE term_id = ?1",
        )?;
        let collected = stmt.query_map(params![term_id], |row| {
            Ok((row.get::<_, String>(0)?, (row.get(1)?, row.get(2)?, row.get(3)?)))
        })?
        .collect::<rusqlite::Result<_>>()?;
        collected
    };

    // --- Nursery learning activities ----------------------------------------
    let activity_names = nursery_activities(&conn)?;
    let mut ratings: HashMap<String, Vec<ActivityRating>> = HashMap::new();
    {
        let mut stmt = conn.prepare(
            "SELECT student_id, activity, rating
             FROM learning_activity_ratings WHERE term_id = ?1",
        )?;
        let rows = stmt.query_map(params![term_id], |row| {
            Ok((
                row.get::<_, String>(0)?,
                ActivityRating {
                    activity: row.get(1)?,
                    rating: row.get(2)?,
                },
            ))
        })?;
        for row in rows {
            let (student_id, rating) = row?;
            ratings.entry(student_id).or_default().push(rating);
        }
    }

    // --- Class teachers, per stream -----------------------------------------
    let class_teachers: Vec<(Option<String>, String)> = {
        let mut stmt = conn.prepare(
            "SELECT ta.stream_id, u.full_name
             FROM teacher_assignments ta
             JOIN users u ON u.id = ta.user_id
             WHERE ta.class_id = ?1 AND ta.role = 'class_teacher' AND ta.status = 'active'",
        )?;
        let collected = stmt
            .query_map(params![class_id], |row| Ok((row.get(0)?, row.get(1)?)))?
            .collect::<rusqlite::Result<_>>()?;
        collected
    };
    let class_teacher_for = |stream_id: &Option<String>| -> Option<String> {
        class_teachers
            .iter()
            .find(|(stream, _)| stream.is_some() && stream == stream_id)
            .or_else(|| class_teachers.iter().find(|(stream, _)| stream.is_none()))
            .map(|(_, name)| name.clone())
    };

    let non_empty = |value: Option<String>| value.filter(|text| !text.trim().is_empty());
    let requirements = non_empty(repo::get_setting(&conn, "report.requirements")?);
    let head_teacher_name = non_empty(repo::get_setting(&conn, "report.head_teacher_name")?);

    // --- Build every card, then rank ----------------------------------------
    let mut cards = Vec::new();
    let mut blocked = Vec::new();

    for learner in &learners {
        if fees_rule_on && learner.fees_blocked && !history {
            blocked.push(BlockedLearner {
                student_id: learner.id.clone(),
                full_name: learner.full_name.clone(),
                reg_number: learner.reg_number.clone(),
                reason: learner
                    .fees_note
                    .clone()
                    .unwrap_or_else(|| "Fees not cleared".into()),
            });
            continue;
        }

        let mut card_subjects = Vec::new();
        let mut graded_for_aggregate: Vec<(bool, GradedMark)> = Vec::new();

        for subject in &subjects {
            let system = systems
                .get(&subject.grading_system_id)
                .ok_or_else(|| AppError::internal("grading system missing"))?;

            let mut exam_scores = Vec::new();
            let mut exam_grades = Vec::new();
            let mut exam_points = Vec::new();
            let mut any_absent = false;

            for (exam_id, _, _, _) in &exams {
                let entry = marks.get(&(
                    learner.id.clone(),
                    subject.id.clone(),
                    exam_id.clone(),
                ));

                let score = entry.and_then(|(score, absent)| if *absent { None } else { *score });
                let absent = entry.map(|(_, absent)| *absent).unwrap_or(false);
                if absent {
                    any_absent = true;
                }
                // Each exam graded on its own, for the per-exam aggregate columns.
                let graded = system.grade(score, absent, subject.max_score, Some(subject.pass_mark));
                exam_grades.push((score.is_some() || absent).then(|| graded.grade_label.clone()));
                exam_points.push(graded.points.filter(|_| score.is_some()));
                exam_scores.push(score);
            }

            let term_score = assessment::term_score(&slots, &exam_scores);

            let graded = system.grade(
                term_score,
                term_score.is_none() && any_absent,
                subject.max_score,
                Some(subject.pass_mark),
            );

            card_subjects.push(ReportCardSubject {
                class_subject_id: subject.id.clone(),
                name: subject.name.clone(),
                is_core: subject.is_core,
                max_score: subject.max_score,
                exam_scores,
                exam_grades,
                exam_points,
                position: None,
                term_score: term_score.map(|s| (s * 100.0).round() / 100.0),
                grade_label: graded.grade_label.clone(),
                points: graded.points,
                remark: graded.remark.clone(),
                teacher_name: subject.teacher_name.clone(),
            });

            graded_for_aggregate.push((subject.is_core, graded));
        }

        let aggregate_input: Vec<(bool, &GradedMark)> = graded_for_aggregate
            .iter()
            .map(|(core, mark)| (*core, mark))
            .collect();
        let totals = grading::aggregate(&aggregate_input);

        let (days_present, days_possible) = attendance
            .get(&learner.id)
            .map(|(present, total)| (Some(*present), Some(*total)))
            .unwrap_or((None, None));

        let (class_comment, head_comment, conduct_comment) = comments
            .get(&learner.id)
            .cloned()
            .unwrap_or((None, None, None));

        let scored: Vec<f64> = card_subjects.iter().filter_map(|s| s.term_score).collect();
        let total_score = (!scored.is_empty())
            .then(|| (scored.iter().sum::<f64>() * 100.0).round() / 100.0);
        let total_max = card_subjects.iter().map(|s| s.max_score).sum();

        // Per-exam totals over the core subjects: marks, aggregate, average.
        let exam_totals: Vec<ExamTotal> = (0..exams.len())
            .map(|index| {
                let core = card_subjects.iter().filter(|s| s.is_core);
                let scored: Vec<(f64, f64)> = core
                    .clone()
                    .filter_map(|s| s.exam_scores[index].map(|score| (score, s.max_score)))
                    .collect();
                let points: Vec<f64> = core.filter_map(|s| s.exam_points[index]).collect();
                ExamTotal {
                    marks: (!scored.is_empty()).then(|| scored.iter().map(|(v, _)| v).sum()),
                    aggregate: (!points.is_empty()).then(|| points.iter().sum()),
                    average: (!scored.is_empty()).then(|| {
                        let pct: f64 = scored.iter().map(|(v, max)| v / max * 100.0).sum();
                        (pct / scored.len() as f64 * 10.0).round() / 10.0
                    }),
                }
            })
            .collect();

        cards.push(ReportCard {
            student_id: learner.id.clone(),
            full_name: learner.full_name.clone(),
            reg_number: learner.reg_number.clone(),
            gender: learner.gender.clone(),
            date_of_birth: learner.date_of_birth.clone(),
            photo_data_url: if photos_on {
                learner
                    .photo
                    .as_ref()
                    .map(|bytes| format!("data:image/png;base64,{}", base64_encode(bytes)))
            } else {
                None
            },
            class_name: class_name.clone(),
            stream_name: learner.stream_name.clone(),
            subjects: card_subjects,
            total_points: totals.total_points,
            mean_percentage: totals.mean_percentage,
            division: totals.division,
            position: None,
            class_size,
            days_present,
            days_possible,
            class_teacher_comment: class_comment,
            head_teacher_comment: head_comment,
            conduct_comment,
            class_teacher_name: class_teacher_for(&learner.stream_id),
            total_score,
            total_max,
            exam_totals,
            previous: None,
            weekly: Vec::new(),
            activities: ratings.remove(&learner.id).unwrap_or_default(),
        });
    }

    rank(&mut cards);
    rank_subjects(&mut cards);

    // --- FR-C12: weekly assignments, for the back page -------------------------
    let mut weekly_weeks = 0;
    if !history && repo::feature_enabled(conn, "weekly_assignments")? {
        let order: Vec<(String, String)> = subjects
            .iter()
            .map(|subject| (subject.id.clone(), subject.name.clone()))
            .collect();
        let (weeks, mut by_student) =
            crate::commands::features::weekly_summaries(conn, term_id, &order)?;
        weekly_weeks = weeks;
        for card in &mut cards {
            card.weekly = by_student.remove(&card.student_id).unwrap_or_default();
        }
    }

    // --- Previous term, for the progress line ---------------------------------
    if !history {
        let previous_term: Option<(String, String)> = conn
            .query_row(
                "SELECT id, name FROM terms
                 WHERE academic_year_id = (SELECT academic_year_id FROM terms WHERE id = ?1)
                   AND seq < ?2
                 ORDER BY seq DESC LIMIT 1",
                params![term_id, term_seq],
                |row| Ok((row.get(0)?, row.get(1)?)),
            )
            .optional()?;
        if let Some((previous_id, previous_name)) = previous_term {
            if let Ok(earlier) = compute_report_cards(conn, class_id, &previous_id, &[], true) {
                let by_student: HashMap<&str, &ReportCard> = earlier
                    .cards
                    .iter()
                    .map(|card| (card.student_id.as_str(), card))
                    .collect();
                for card in &mut cards {
                    if let Some(before) = by_student.get(card.student_id.as_str()) {
                        if before.mean_percentage.is_some() {
                            card.previous = Some(PreviousTerm {
                                term_name: previous_name.clone(),
                                total_points: before.total_points,
                                division: before.division.clone(),
                                mean_percentage: before.mean_percentage,
                                position: before.position,
                                class_size: before.class_size,
                            });
                        }
                    }
                }
            }
        }
    }

    // --- Class averages -------------------------------------------------------
    let mean_of = |values: Vec<f64>| -> Option<f64> {
        (!values.is_empty())
            .then(|| (values.iter().sum::<f64>() / values.len() as f64 * 10.0).round() / 10.0)
    };
    let class_average = mean_of(cards.iter().filter_map(|c| c.mean_percentage).collect());
    let exam_class_averages: Vec<Option<f64>> = (0..exams.len())
        .map(|index| {
            mean_of(
                cards
                    .iter()
                    .filter_map(|c| c.exam_totals.get(index).and_then(|t| t.average))
                    .collect(),
            )
        })
        .collect();

    // The key printed at the foot: the class's own grading scale.
    let grade_key: Vec<GradeKeyBand> = subjects
        .iter()
        .find(|subject| subject.is_core)
        .or_else(|| subjects.first())
        .and_then(|subject| systems.get(&subject.grading_system_id))
        .map(|system| {
            system
                .bands
                .iter()
                .map(|band| GradeKeyBand {
                    label: band.label.clone(),
                    lower: band.lower_bound,
                    upper: band.upper_bound,
                    points: band.points,
                })
                .collect()
        })
        .unwrap_or_default();

    Ok(ReportCardBatch {
        class_name,
        level_kind,
        activity_names,
        next_term_begins,
        requirements,
        head_teacher_name,
        class_average,
        exam_class_averages,
        grade_key,
        weekly_weeks,
        stream_name: None,
        term_name,
        academic_year,
        exam_names: exams.iter().map(|(_, name, _, _)| name.clone()).collect(),
        is_final,
        cards,
        blocked,
    })
}


/// Each learner's place in the class for each subject, by term mark.
fn rank_subjects(cards: &mut [ReportCard]) {
    let Some(subject_count) = cards.first().map(|card| card.subjects.len()) else {
        return;
    };
    for index in 0..subject_count {
        let mut scores: Vec<f64> = cards
            .iter()
            .filter_map(|card| card.subjects.get(index).and_then(|s| s.term_score))
            .collect();
        scores.sort_by(|a, b| b.partial_cmp(a).unwrap_or(std::cmp::Ordering::Equal));
        for card in cards.iter_mut() {
            if let Some(subject) = card.subjects.get_mut(index) {
                subject.position = subject.term_score.map(|mine| {
                    // 1 + how many did strictly better: ties share a place.
                    1 + scores.iter().filter(|&&other| other > mine).count() as i64
                });
            }
        }
    }
}

/// Class position.
///
/// Where the grading system has points (UNEB), a lower aggregate is better.
/// Otherwise a higher mean percentage is better. Equal results share a
/// position and the next position skips accordingly — 1, 2, 2, 4 — which is
/// how a Ugandan report card reads.
fn rank(cards: &mut [ReportCard]) {
    let use_points = cards.iter().any(|card| card.total_points.is_some());

    let mut order: Vec<usize> = (0..cards.len()).collect();
    order.sort_by(|&a, &b| {
        if use_points {
            match (cards[a].total_points, cards[b].total_points) {
                (Some(x), Some(y)) => x.partial_cmp(&y).unwrap_or(std::cmp::Ordering::Equal),
                (Some(_), None) => std::cmp::Ordering::Less,
                (None, Some(_)) => std::cmp::Ordering::Greater,
                (None, None) => std::cmp::Ordering::Equal,
            }
        } else {
            match (cards[a].mean_percentage, cards[b].mean_percentage) {
                (Some(x), Some(y)) => y.partial_cmp(&x).unwrap_or(std::cmp::Ordering::Equal),
                (Some(_), None) => std::cmp::Ordering::Less,
                (None, Some(_)) => std::cmp::Ordering::Greater,
                (None, None) => std::cmp::Ordering::Equal,
            }
        }
    });

    let key = |card: &ReportCard| -> Option<i64> {
        if use_points {
            card.total_points.map(|p| (p * 100.0).round() as i64)
        } else {
            card.mean_percentage.map(|p| (p * 100.0).round() as i64)
        }
    };

    let mut last_key: Option<Option<i64>> = None;
    let mut last_position = 0i64;

    for (index, &card_index) in order.iter().enumerate() {
        let this_key = key(&cards[card_index]);
        if this_key.is_none() {
            cards[card_index].position = None;
            continue;
        }
        let position = if Some(this_key) == last_key {
            last_position
        } else {
            index as i64 + 1
        };
        cards[card_index].position = Some(position);
        last_key = Some(this_key);
        last_position = position;
    }
}

