#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ClassListBody {
    pub class_name: String,
    pub academic_year: String,
    pub term_name: Option<String>,
    pub rows: Vec<ClassListRow>,
    pub total: usize,
    pub boys: usize,
    pub girls: usize,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ClassListRow {
    pub number: usize,
    pub reg_number: String,
    pub full_name: String,
    pub gender: Option<String>,
    pub guardian_name: Option<String>,
    pub guardian_phone: Option<String>,
}

#[tauri::command]
pub fn build_class_list(
    state: State<'_, AppState>,
    class_id: String,
) -> AppResult<DocumentEnvelope<ClassListBody>> {
    let session = state.sessions.require()?;
    session.require_view_class(&class_id)?;

    let conn = state.db.lock();
    let year_id = repo::current_academic_year_id(&conn)?
        .ok_or_else(|| AppError::validation("No academic year is active yet."))?;

    let (class_name, academic_year): (String, String) = conn.query_row(
        "SELECT c.name, y.label FROM classes c, academic_years y WHERE c.id = ?1 AND y.id = ?2",
        params![class_id, year_id],
        |row| Ok((row.get(0)?, row.get(1)?)),
    )?;

    let term_name: Option<String> = match repo::current_term_id(&conn)? {
        Some(term_id) => conn
            .query_row(
                "SELECT name FROM terms WHERE id = ?1",
                params![term_id],
                |row| row.get(0),
            )
            .optional()?,
        None => None,
    };

    let mut stmt = conn.prepare(
        "SELECT s.reg_number, s.full_name, s.gender, s.guardian_name, s.guardian_phone
         FROM enrollments e JOIN students s ON s.id = e.student_id
         WHERE e.class_id = ?1 AND e.academic_year_id = ?2 AND e.status = 'active'
         ORDER BY s.full_name COLLATE NOCASE ASC",
    )?;

    let rows: Vec<ClassListRow> = stmt
        .query_map(params![class_id, year_id], |row| {
            Ok(ClassListRow {
                number: 0,
                reg_number: row.get(0)?,
                full_name: row.get(1)?,
                gender: row.get(2)?,
                guardian_name: row.get(3)?,
                guardian_phone: row.get(4)?,
            })
        })?
        .collect::<rusqlite::Result<Vec<_>>>()?
        .into_iter()
        .enumerate()
        .map(|(index, mut row)| {
            row.number = index + 1;
            row
        })
        .collect();
    drop(stmt);

    let boys = rows.iter().filter(|r| r.gender.as_deref() == Some("M")).count();
    let girls = rows.iter().filter(|r| r.gender.as_deref() == Some("F")).count();

    let body = ClassListBody {
        class_name,
        academic_year,
        term_name,
        total: rows.len(),
        boys,
        girls,
        rows,
    };

    envelope(&conn, "class_list", body)
}

