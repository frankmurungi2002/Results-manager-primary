/// The only shape a printable document ever takes.
///
/// `branding` and `footer` are not optional and are filled by the backend, so
/// a caller cannot construct a document without them. Third-party or sponsor
/// attribution has no field to live in — FR-D4 forbids it for every school.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DocumentEnvelope<T> {
    pub branding: Branding,
    pub footer: Footer,
    pub document_kind: String,
    pub body: T,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Branding {
    pub institution_name: String,
    pub motto: Option<String>,
    /// `data:image/png;base64,…`, or none when the school has no logo.
    pub logo_data_url: Option<String>,
    pub accent_color: String,
    pub address: Option<String>,
    pub phone: Option<String>,
    pub email: Option<String>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Footer {
    /// Fixed text. Deliberately not configurable.
    pub generated_by: String,
    pub printed_on: String,
    pub app_version: String,
}

fn load_branding(conn: &Connection) -> AppResult<Branding> {
    type Raw = (
        String,
        Option<String>,
        Option<Vec<u8>>,
        String,
        Option<String>,
        Option<String>,
        Option<String>,
    );

    let raw: Raw = conn
        .query_row(
            "SELECT name, motto, logo_png, accent_color, address, phone, email
             FROM institution WHERE id = 1",
            [],
            |row| {
                Ok((
                    row.get(0)?,
                    row.get(1)?,
                    row.get(2)?,
                    row.get(3)?,
                    row.get(4)?,
                    row.get(5)?,
                    row.get(6)?,
                ))
            },
        )
        .optional()?
        .ok_or(AppError::NotProvisioned)?;

    Ok(Branding {
        institution_name: raw.0,
        motto: raw.1,
        logo_data_url: raw
            .2
            .map(|bytes| format!("data:image/png;base64,{}", base64_encode(&bytes))),
        accent_color: raw.3,
        address: raw.4,
        phone: raw.5,
        email: raw.6,
    })
}

fn footer() -> Footer {
    Footer {
        generated_by: "Generated by Phantom School Manager".into(),
        printed_on: Utc::now().format("%d %B %Y").to_string(),
        app_version: env!("CARGO_PKG_VERSION").to_string(),
    }
}

/// Wraps a body in branding. Every document-producing command ends here.
pub(crate) fn envelope<T>(conn: &Connection, kind: &str, body: T) -> AppResult<DocumentEnvelope<T>> {
    Ok(DocumentEnvelope {
        branding: load_branding(conn)?,
        footer: footer(),
        document_kind: kind.to_string(),
        body,
    })
}

